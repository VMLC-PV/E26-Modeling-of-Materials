@app.cell(hide_code=True)
def _(mo):
    mo.md(r"""
    **From the gradient to an algorithm.** Two refinements turn this into a robust method:

    1. **Fitness shaping.** Replace the values $f(x_i)$ by weights $u_i$ that depend only on the **rank** of $x_i$ in the population (best = largest $u_i$), standardized to mean 0 and standard deviation 1. The algorithm then behaves the same for $f$ and for any increasing function of $f$ (e.g. $\ln f$ or $f^3$), and one outlier, frequent on the Rosenbrock function, cannot dominate the update. With the sign flipped (we minimize), good samples pull the mean towards them, bad ones push it away.
    2. **Natural step sizes.** A gradient step in $\mu$ should be measured in units of $\sigma$, and $\sigma$ should be updated multiplicatively so it stays positive. This leads to (the *natural gradient*, which accounts for the geometry of the Gaussian family)
    $$
    \mu \leftarrow \mu + \alpha_\mu\, \sigma \, \frac{1}{\lambda}\sum_i u_i z_i, \qquad
    \sigma \leftarrow \sigma \exp\!\left[\frac{\alpha_\sigma}{2}\,\frac{1}{\lambda}\sum_i u_i\left(\frac{\|z_i\|^2}{d} - 1\right)\right].
    $$

    The $\sigma$ update reads like the 1/5 rule. The factor $\|z_i\|^2/d - 1$ is positive for samples further than $\sigma\sqrt{d}$ from the mean and negative for closer ones: **if the good samples are far away**, $\sigma$ grows (explore); **if they are close**, $\sigma$ shrinks (exploit). The learning rates $\alpha_\mu, \alpha_\sigma$ are of order 1.
    """)
    return


@app.cell
def _(np):
    def rank_weights(f_values):
        """Fitness shaping: weights from the ranks (best = largest), mean 0 and standard deviation 1."""
        ranks = np.argsort(np.argsort(f_values))  # 0 = lowest f = best
        u = -(ranks - ranks.mean())
        return u / u.std()

    def zscore_weights(f_values):
        """Weights from the f values themselves, standardized (no fitness shaping)."""
        return -(f_values - f_values.mean()) / (f_values.std() + 1e-300)

    def search_gradient_es(f, mu0, sigma0, lam, n_gen, rng, alpha_mu=1.0, alpha_sigma=1.0, weights=rank_weights):
        """Isotropic search-gradient ES. Returns one dict per generation."""
        mu, sigma = np.array(mu0, dtype=float), float(sigma0)
        d = mu.size
        history = []
        for _ in range(n_gen):
            z = rng.standard_normal((lam, d))
            x = mu + sigma * z
            fx = f(x)
            u = weights(fx)
            history.append(dict(mu=mu.copy(), sigma=sigma, z=z, x=x, f=fx, u=u))
            mu = mu + alpha_mu * sigma * np.mean(u[:, None] * z, axis=0)
            sigma = sigma * np.exp(alpha_sigma / 2 * np.mean(u * (np.sum(z**2, axis=1) / d - 1)))
        return history

    return rank_weights, search_gradient_es, zscore_weights


