@app.cell(hide_code=True)
def _(mo):
    mo.md(r"""
    ## 4. Covariance matrix adaptation (CMA-ES)
    ---

    CMA-ES is the standard modern evolution strategy. It samples from a Gaussian with a full **covariance matrix** $C$,
    $$
    x_i = m + \sigma y_i, \qquad y_i \sim \mathcal{N}(0, C),
    $$
    so the search distribution is an ellipsoid that can stretch and rotate to fit the landscape. Sampling $y \sim \mathcal{N}(0, C)$ uses the eigendecomposition $C = B D^2 B^\top$: $y = B D z$ with $z \sim \mathcal{N}(0, I)$ (the same idea as the Cholesky factor used to sample Gaussian processes in lecture 12).

    One generation, with $\lambda$ samples sorted from best ($y_{1:\lambda}$) to worst, and positive weights $w_1 \ge \ldots \ge w_\mu$ on the best half ($\mu = \lambda/2$, $\sum w_i = 1$):

    1. **Mean**: move to the weighted average of the best samples,
    $m \leftarrow m + \sigma\, \langle y \rangle_w$, with $\langle y \rangle_w = \sum_{i=1}^{\mu} w_i\, y_{i:\lambda}$.
    2. **Covariance**: make the successful steps more likely,
    $$
    C \leftarrow (1 - c_1 - c_\mu)\, C + c_1\, p_c p_c^\top + c_\mu \sum_{i=1}^{\mu} w_i\, y_{i:\lambda} y_{i:\lambda}^\top .
    $$
    The last term (**rank-μ update**) is the covariance of the selected steps: directions in which good samples were found get a larger variance. The **evolution path** $p_c$ is an exponentially smoothed sum of the recent mean steps $\langle y \rangle_w$. If successive steps point the same way, as along a long valley, $p_c$ grows and the rank-one term $p_c p_c^\top$ stretches $C$ along that direction.
    3. **Step size** (cumulative step-size adaptation): a second evolution path $p_\sigma$ sums the recent steps in "whitened" coordinates, $C^{-1/2}\langle y \rangle_w$. Under purely random selection its length would be that of a standard Gaussian vector, $\mathbb{E}\|\mathcal{N}(0, I)\| \approx \sqrt{d}$. Consecutive steps pointing the same way (path longer than that) mean the steps are too small; steps that cancel (shorter path) mean they are too large:
    $$
    \sigma \leftarrow \sigma \exp\!\left[\frac{c_\sigma}{d_\sigma}\left(\frac{\|p_\sigma\|}{\mathbb{E}\|\mathcal{N}(0, I)\|} - 1\right)\right].
    $$

    The learning rates $c_1, c_\mu, c_c, c_\sigma, d_\sigma$, the weights and the default population size $\lambda = 4 + \lfloor 3\ln d\rfloor$ have well-tested default values that depend only on the dimension $d$; we use those of N. Hansen, *The CMA Evolution Strategy: A Tutorial* (arXiv:1604.00772). The user chooses only the starting point $m$ and the initial step size $\sigma$. CMA-ES is invariant under rotations of the coordinates and, thanks to the rank-based selection, under increasing transformations of $f$. For production work, use a library: pymoo's `CMAES`, built on the `cma` package, adds bound handling, restarts and many safeguards. Our implementation is checked against it below.
    """)
    return


@app.cell
def _(np):
    def cma_es(f, m0, sigma0, rng, lam=None, max_eval=10_000, record=False):
        """Minimize f: R^d -> R with CMA-ES (default parameters of Hansen's tutorial).

        Stops when the budget is spent, when the search distribution has shrunk to nothing,
        or when the best value has stagnated. Returns a dict with the best point and value,
        the final mean m, the number of evaluations, the best-so-far after each generation and, if `record`,
        the state of each generation."""
        m = np.array(m0, dtype=float)
        d, sigma = m.size, float(sigma0)
        lam = lam or 4 + int(3 * np.log(d))
        mu = lam // 2
        w = np.log(mu + 0.5) - np.log(np.arange(1, mu + 1))
        w /= w.sum()
        mueff = 1 / np.sum(w**2)  # effective number of selected samples
        cc = (4 + mueff / d) / (d + 4 + 2 * mueff / d)
        cs = (mueff + 2) / (d + mueff + 5)
        c1 = 2 / ((d + 1.3) ** 2 + mueff)
        cmu = min(1 - c1, 2 * (mueff - 2 + 1 / mueff) / ((d + 2) ** 2 + mueff))
        ds = 1 + 2 * max(0, np.sqrt((mueff - 1) / (d + 1)) - 1) + cs
        chi_d = np.sqrt(d) * (1 - 1 / (4 * d) + 1 / (21 * d**2))  # E||N(0, I)||

        pc, ps, C = np.zeros(d), np.zeros(d), np.eye(d)
        n_eval, gen = 0, 0
        x_best, f_best = m.copy(), np.inf
        trace_n, trace_f, gen_best, states = [], [], [], []
        stall = 10 + int(30 * d / lam)  # generations without progress before stopping
        while n_eval + lam <= max_eval:
            D2, B = np.linalg.eigh(C)
            D = np.sqrt(np.maximum(D2, 1e-30))
            y = rng.standard_normal((lam, d)) @ (B * D).T  # y_i ~ N(0, C)
            x = m + sigma * y
            fx = f(x)
            n_eval += lam
            if fx.min() < f_best:
                f_best, x_best = fx.min(), x[np.argmin(fx)].copy()
            trace_n.append(n_eval)
            trace_f.append(f_best)
            gen_best.append(fx.min())
            if record:
                states.append(dict(m=m.copy(), sigma=sigma, C=C.copy(), x=x))

            best = np.argsort(fx)[:mu]  # selection
            y_w = w @ y[best]
            m = m + sigma * y_w
            ps = (1 - cs) * ps + np.sqrt(cs * (2 - cs) * mueff) * (B @ ((B.T @ y_w) / D))  # C^(-1/2) y_w
            h = np.linalg.norm(ps) / np.sqrt(1 - (1 - cs) ** (2 * (gen + 1))) / chi_d < 1.4 + 2 / (d + 1)
            pc = (1 - cc) * pc + h * np.sqrt(cc * (2 - cc) * mueff) * y_w
            C = (1 - c1 - cmu) * C + c1 * (np.outer(pc, pc) + (1 - h) * cc * (2 - cc) * C) + cmu * (y[best].T * w) @ y[best]
            C = (C + C.T) / 2
            sigma *= np.exp(cs / ds * (np.linalg.norm(ps) / chi_d - 1))
            gen += 1
            if sigma * np.sqrt(D2.max()) < 1e-10 * max(1.0, np.abs(m).max()):
                break  # the search distribution has collapsed
            if gen > stall and np.ptp(gen_best[-stall:]) < 1e-12 * max(1.0, abs(f_best)):
                break  # the best value of each generation no longer changes
        return dict(x=x_best, f=f_best, m=m, n_eval=n_eval, lam=lam, trace_n=np.array(trace_n), trace_f=np.array(trace_f), states=states)

    return (cma_es,)


