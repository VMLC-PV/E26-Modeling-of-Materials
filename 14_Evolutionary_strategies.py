@app.cell
def _(np):
    def family_tree_es(f, mu, lam, n_gen, sigma0, rng, plus=False, tau=1 / np.sqrt(2)):
        """1D self-adaptive (mu, lambda)- or (mu + lambda)-ES on [0, 1] with one parent per offspring.

        f      : function to minimize, vectorized (takes an array of x, returns an array of f)
        mu     : number of parents (survivors kept after each selection)
        lam    : number of offspring created in each generation
        n_gen  : number of generations
        sigma0 : initial step size of every individual
        plus   : False for comma selection (only offspring survive), True for plus selection
        tau    : learning rate of the step sizes. Each sigma is multiplied by exp(tau * N(0, 1)).
                 The usual rule of thumb is tau = 1/sqrt(2 d) for d variables, here d = 1.
                 With tau ~ 0.7, a child's sigma is typically 2 times larger or smaller than its
                 parent's: big enough for sigma to adapt within a few generations, small enough
                 that a child stays similar to its parent (heredity), so selection can act on sigma.

        Returns one dict per generation (generation 0 = initial population) with:
          x, s, f   : position, step size and function value of every candidate of the generation
          parent    : for each candidate, its index in the previous generation's lists (-1: none)
          survivors : indices of the mu best candidates, the parents of the next generation
        """
        # Generation 0: mu random individuals, all with the same step size; all of them survive
        x = rng.uniform(0, 1, mu)
        s = np.full(mu, sigma0)
        generations = [dict(x=x, s=s, f=f(x), parent=np.full(mu, -1), survivors=np.arange(mu))]

        for _ in range(n_gen):
            prev = generations[-1]

            # 1. Parent choice: each of the lam offspring picks one of the mu survivors at random.
            #    k is a position in the survivor list; par is the index in the previous generation.
            k = rng.integers(mu, size=lam)
            par = prev["survivors"][k]

            # 2. Mutation of the step size first (self-adaptation): the child inherits its parent's
            #    sigma, multiplied by a random log-normal factor (always positive).
            s_new = prev["s"][par] * np.exp(tau * rng.standard_normal(lam))

            # 3. Mutation of the position, with the child's *new* step size. A child whose sigma
            #    suits the landscape tends to land well, survive, and pass that sigma on.
            x_new = prev["x"][par] + s_new * rng.standard_normal(lam)

            # 4. Keep the children inside [0, 1] by reflecting at the walls (as a light ray between
            #    two mirrors): fold onto [0, 2), then mirror the part in (1, 2) back onto (0, 1).
            x_new = np.mod(x_new, 2)
            x_new = np.where(x_new > 1, 2 - x_new, x_new)

            # 5. Plus selection: the parents join the pool and compete with their own offspring.
            #    A parent kept this way is recorded as its own "child" (same x and sigma).
            if plus:
                x_new = np.concatenate([x_new, prev["x"][prev["survivors"]]])
                s_new = np.concatenate([s_new, prev["s"][prev["survivors"]]])
                par = np.concatenate([par, prev["survivors"]])

            # 6. Evaluation and selection: the mu candidates with the lowest f survive.
            f_new = f(x_new)
            survivors = np.argsort(f_new)[:mu]
            generations.append(dict(x=x_new, s=s_new, f=f_new, parent=par, survivors=survivors))
        return generations

    return (family_tree_es,)


