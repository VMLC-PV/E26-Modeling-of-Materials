@app.cell(hide_code=True)
def _(mo):
    mo.md(r"""
    ## 3. Evolution as a search gradient
    ---

    Instead of one offspring, we now sample a whole **population** of $\lambda$ candidates from a Gaussian **search distribution** with mean $\mu$ and width $\sigma$,
    $$
    x_i = \mu + \sigma z_i, \qquad z_i \sim \mathcal{N}(0, I), \qquad i = 1, \ldots, \lambda,
    $$
    and we let the whole distribution move. Which way? Consider the average of $f$ over the search distribution,
    $$
    J(\mu, \sigma) = \mathbb{E}_{x \sim \mathcal{N}(\mu, \sigma^2 I)}\left[f(x)\right] = \int f(x)\, p(x \mid \mu, \sigma)\, dx .
    $$
    Here $\mathbb{E}_{x \sim p}[g(x)] = \int g(x)\, p(x)\, dx$ denotes the **expectation** (mean value) of $g(x)$ when $x$ is drawn from the probability density $p$; the subscript names the random variable and its distribution, and is dropped when it is clear from the context. $p(x \mid \mu, \sigma)$ is the Gaussian density of the search distribution.
    $J$ is a **smoothed** version of $f$: details smaller than $\sigma$ (noise, small local minima) are averaged out. We minimize $J$ by gradient descent, and its gradient needs **no derivative of $f$**: only the Gaussian is differentiated (the "log-likelihood trick", with the likelihood of lecture 11),
    $$
    \nabla_\theta J = \int f(x)\, \nabla_\theta p\, dx = \int f(x)\, p\, \nabla_\theta \ln p\, dx = \mathbb{E}\left[f(x)\, \nabla_\theta \ln p(x \mid \theta)\right].
    $$
    For the Gaussian in $d$ dimensions, $\ln p = -\|x - \mu\|^2/(2\sigma^2) - d\ln\sigma + \text{const}$, so
    $$
    \nabla_\mu \ln p = \frac{z}{\sigma}, \qquad \frac{\partial \ln p}{\partial \sigma} = \frac{\|z\|^2 - d}{\sigma}.
    $$
    The expectation is estimated by Monte Carlo (lecture 10) over the population:
    $$
    \nabla_\mu J \approx \frac{1}{\lambda\sigma}\sum_i f(x_i)\, z_i, \qquad \frac{\partial J}{\partial \sigma} \approx \frac{1}{\lambda\sigma}\sum_i f(x_i)\left(\|z_i\|^2 - d\right).
    $$
    Each sample "votes" for its direction $z_i$ with weight $f(x_i)$. Subtracting a constant from $f$ (the population mean $\bar f$, a **baseline**) does not change the expectation, since $\mathbb{E}[\nabla_\theta \ln p] = 0$, but greatly reduces the Monte Carlo noise. A check on the sphere, for which $J = \|\mu\|^2 + d\sigma^2$ exactly, so $\nabla_\mu J = 2\mu$ and $\partial J/\partial\sigma = 2d\sigma$:
    """)
    return


