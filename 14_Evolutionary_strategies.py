@app.cell(hide_code=True)
def _(Callback, Problem, np, pymoo_minimize):
    class FunctionProblem(Problem):
        """A vectorized function f(X), X of shape (n, d), as a pymoo problem on the box [lower, upper]^d."""

        def __init__(self, f, d, lower, upper):
            super().__init__(n_var=d, n_obj=1, xl=np.full(d, float(lower)), xu=np.full(d, float(upper)))
            self.f = f

        def _evaluate(self, X, out, *args, **kwargs):
            out["F"] = self.f(X)

    class History(Callback):
        """Records, after each generation, the evaluations so far, the best value so far and (optionally) the population."""

        def __init__(self, keep_population=False):
            super().__init__()
            self.keep_population = keep_population
            self.n_eval, self.f_best, self.populations = [], [], []

        def notify(self, algorithm):
            self.n_eval.append(algorithm.evaluator.n_eval)
            self.f_best.append(algorithm.opt.get("F").min())
            if self.keep_population:
                self.populations.append(algorithm.pop.get("X").copy())

    def run_pymoo(problem, algorithm, max_eval, seed, keep_population=False):
        """Run a pymoo algorithm with a budget of evaluations; returns the best point and the history."""
        history = History(keep_population)
        # seed + 1: the cma package behind CMAES treats seed 0 as "random seed from the clock"
        result = pymoo_minimize(problem, algorithm, ("n_evals", max_eval), seed=seed + 1, callback=history, verbose=False)
        return dict(
            x=np.atleast_2d(result.X)[0], f=float(np.min(result.F)),
            n_eval=np.array(history.n_eval), f_best=np.minimum.accumulate(history.f_best), populations=history.populations,
        )

    return FunctionProblem, run_pymoo


