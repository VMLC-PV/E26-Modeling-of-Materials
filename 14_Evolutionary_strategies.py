@app.cell(hide_code=True)
def _(mo):
    mo.md(r"""
    ## Summary: Evolutionary strategies

    **The evolutionary loop**: evaluate a population, select the best as parents, create offspring by recombination and mutation, repeat. Evolutionary strategies work on real-valued vectors with Gaussian mutations, and adapt the mutation distribution as they go.

    **The methods**

    | Method | Search distribution | Adaptation | In this lecture |
    |---|---|---|---|
    | (1+1)-ES | one offspring, $\mathcal{N}(x, \sigma^2 I)$ | $\sigma$ by the 1/5 success rule | numpy |
    | Self-adaptive $(\mu, \lambda)$-ES | each individual carries its own $\sigma$ | $\sigma$ mutated and selected with $x$ | numpy (family tree), pymoo `ES` |
    | Search-gradient ES | population, $\mathcal{N}(\mu, \sigma^2 I)$ | $\mu, \sigma$ by a Monte Carlo gradient of $J = \mathbb{E}[f]$ | numpy |
    | CMA-ES | population, $\mathcal{N}(m, \sigma^2 C)$ | $m$ by weighted recombination, $C$ by rank-one and rank-$\mu$ updates, $\sigma$ by the evolution path | numpy, pymoo `CMAES` |
    | IPOP-CMA-ES | as CMA-ES | restarts with doubled population size | pymoo `CMAES(restarts=..., incpopsize=2)` |

    **Key ideas**

    - The algorithm learns *how to search*: the step size (and shape) of the mutations follows the landscape, so convergence is geometric near a minimum, without a schedule fixed in advance.
    - Only the **ranks** of the $f$ values are used: the methods are insensitive to outliers and to any increasing transformation of $f$.
    - A population averages $f$ over the search distribution, which smooths out small local minima: large populations are more global, small ones more efficient.
    - Restarts with increasing population size remove the need to choose $\lambda$.

    **When to use them**: continuous variables, from a few to a few hundred; no gradients, or a rugged or noisy function; evaluations cheap enough for thousands to millions of them. CMA-ES (pymoo `CMAES`, or the `cma` package it is built on) is the default choice. For a few expensive evaluations, use Bayesian optimization (lecture 13); for a smooth function with a gradient, use a gradient method. pymoo also provides genetic algorithms, differential evolution and, for several objectives at once, multi-objective algorithms such as NSGA-II.
    """)
    return


