@app.cell(hide_code=True)
def _(mo):
    mo.md(r"""
    ## 2. The (1+1) evolution strategy
    ---

    The simplest ES keeps a single **parent** $x$ and, at each step, creates one **offspring** by a Gaussian mutation,
    $$
    y = x + \sigma z, \qquad z \sim \mathcal{N}(0, I),
    $$
    and keeps the better of the two (**selection**): if $f(y) \le f(x)$, then $x \leftarrow y$. The name (1+1) means one parent plus one offspring compete. Only downhill moves are accepted.

    The whole difficulty is the **step size** $\sigma$. If it is too large, almost every offspring lands uphill and nothing happens. If it is too small, nearly half the offspring are improvements (for a smooth $f$, half of the directions go downhill) but each improvement is tiny. In between there is a step size with the fastest progress, which corresponds to a probability of success of about 1/5. Hence the **1/5 success rule**, due to Rechenberg, one of the founders of ES:

    - after a success, increase $\sigma$: $\sigma \leftarrow \sigma\, e^{1/3}$;
    - after a failure, decrease it: $\sigma \leftarrow \sigma\, e^{-1/12}$.

    If one trial in five succeeds, the factors cancel, $e^{1/3}\,(e^{-1/12})^4 = 1$; more successes make $\sigma$ grow, fewer make it shrink. The ratio of the exponents (4 : 1) fixes the target rate of 1/5; their size sets how fast $\sigma$ reacts. With these values, $\sigma$ is divided by 10 after about 28 failures in a row and multiplied by 10 after about 7 successes in a row: quick compared with a run of hundreds of evaluations, yet one lucky trial changes $\sigma$ by only 40%. Since $\sigma$ follows the distance to the minimum, both shrink together **geometrically**: a straight line on a log scale (linear convergence), as for the bisection method.
    """)
    return


@app.cell
def _(np):
    def one_plus_one_es(f, x0, sigma0, n_eval, rng, adapt=True):
        """(1+1)-ES with the 1/5 success rule.

        f      : function to minimize, taking one point x (array of d coordinates) and returning f(x)
        x0     : starting point (the first parent)
        sigma0 : initial step size
        n_eval : total number of evaluations of f (the starting point included)
        adapt  : True to adapt sigma with the 1/5 success rule, False to keep sigma = sigma0
                 With adaptation, sigma is multiplied by exp(1/3) after a success and by
                 exp(-1/12) after a failure. The ratio of the two exponents, 1/3 : 1/12 = 4 : 1,
                 makes sigma constant on average exactly when 1 trial in 5 succeeds. Their size
                 sets the speed: without successes sigma is divided by 10 in about
                 12 ln(10) = 28 evaluations, and multiplied by 10 after about 7 successes in a row.
                 That is fast compared with the hundreds of evaluations of a run, but slow enough
                 that one lucky (or unlucky) trial does not change sigma much.

        Returns, as arrays with one entry per evaluation: the parent X, its value F, the step size S,
        and (one entry per trial, i.e. n_eval - 1) whether the offspring was accepted.
        """
        # The first parent is the starting point
        x = np.array(x0, dtype=float)
        fx, sigma = f(x), sigma0
        X, F, S, success = [x], [fx], [sigma], []

        for _ in range(n_eval - 1):
            # 1. Mutation: one offspring, a Gaussian step of size sigma in a random direction
            y = x + sigma * rng.standard_normal(x.size)
            fy = f(y)

            # 2. Selection: the offspring replaces the parent if it is at least as good.
            #    Accepting equal values (<=) lets the search move across flat regions.
            success.append(fy <= fx)
            if fy <= fx:
                x, fx = y, fy

            # 3. Step-size control (1/5 rule): larger steps after a success, smaller after a failure
            if adapt:
                sigma *= np.exp(1 / 3) if success[-1] else np.exp(-1 / 12)

            # Record the current parent, its value and the step size for the plots
            X.append(x)
            F.append(fx)
            S.append(sigma)
        return np.array(X), np.array(F), np.array(S), np.array(success)

    return (one_plus_one_es,)


